package dev.bootloaderstudio.app.data

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Symmetric cipher used to protect the persisted Xiaomi session.
 *
 * The interface keeps the Android Keystore implementation replaceable so the
 * session codec and storage migration can be tested on the JVM.
 */
interface SessionCipher {
    fun encrypt(plaintext: ByteArray): ByteArray

    fun decrypt(ciphertext: ByteArray): ByteArray
}

/**
 * AES/GCM cipher backed by a non-exportable Android Keystore key.
 *
 * The stored blob is: [format version][12-byte IV][GCM ciphertext + tag].
 * A fresh IV is generated by the Keystore for every encryption because
 * randomized encryption is required.
 */
class AndroidKeystoreSessionCipher(
    private val keyAlias: String = DEFAULT_KEY_ALIAS
) : SessionCipher {

    override fun encrypt(plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey())
        val iv = cipher.iv
        val encrypted = cipher.doFinal(plaintext)

        return ByteArray(1 + iv.size + encrypted.size).also { output ->
            output[0] = FORMAT_VERSION
            iv.copyInto(output, destinationOffset = 1)
            encrypted.copyInto(output, destinationOffset = 1 + iv.size)
        }
    }

    override fun decrypt(ciphertext: ByteArray): ByteArray {
        require(ciphertext.size > 1 + GCM_IV_BYTES) { "Encrypted session is too short." }
        require(ciphertext[0] == FORMAT_VERSION) { "Unsupported encrypted session format." }

        val iv = ciphertext.copyOfRange(1, 1 + GCM_IV_BYTES)
        val payload = ciphertext.copyOfRange(1 + GCM_IV_BYTES, ciphertext.size)

        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, getOrCreateKey(), GCMParameterSpec(GCM_TAG_BITS, iv))
        return cipher.doFinal(payload)
    }

    private fun getOrCreateKey(): SecretKey {
        val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }
        val existing = keyStore.getEntry(keyAlias, null) as? KeyStore.SecretKeyEntry
        if (existing != null) return existing.secretKey

        val generator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            KEYSTORE_PROVIDER
        )
        generator.init(
            KeyGenParameterSpec.Builder(
                keyAlias,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                .setRandomizedEncryptionRequired(true)
                .build()
        )
        return generator.generateKey()
    }

    companion object {
        private const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val DEFAULT_KEY_ALIAS = "bootloader_studio_session"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val FORMAT_VERSION: Byte = 1
        private const val GCM_IV_BYTES = 12
        private const val GCM_TAG_BITS = 128
        private const val KEY_SIZE_BITS = 256
    }
}
